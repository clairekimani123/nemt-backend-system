"""Shared address columns (+ PostGIS point) and schemas, reused by facilities,
patient addresses, and later trips/stops."""

from datetime import UTC, datetime
from typing import Any

from geoalchemy2 import Geography
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator
from sqlalchemy import Computed, Float, String
from sqlalchemy.orm import Mapped, mapped_column

from app.core.geo import get_geocoder, point


class AddressMixin:
    line1: Mapped[str] = mapped_column(String(200))
    line2: Mapped[str | None] = mapped_column(String(200))
    city: Mapped[str] = mapped_column(String(100))
    state: Mapped[str] = mapped_column(String(2))
    postal_code: Mapped[str] = mapped_column(String(10))
    # geography(Point,4326): distances in METRES on the real earth, not degrees
    location: Mapped[Any | None] = mapped_column(Geography("POINT", srid=4326, spatial_index=False))
    # read-only convenience columns generated by Postgres from `location`
    latitude: Mapped[float | None] = mapped_column(Float, Computed("ST_Y(location::geometry)", persisted=True))
    longitude: Mapped[float | None] = mapped_column(Float, Computed("ST_X(location::geometry)", persisted=True))
    geocode_status: Mapped[str] = mapped_column(String(10), default="none", server_default="none")


class AddressIn(BaseModel):
    line1: str = Field(min_length=1, max_length=200)
    line2: str | None = Field(default=None, max_length=200)
    city: str = Field(min_length=1, max_length=100)
    state: str = Field(pattern=r"^[A-Za-z]{2}$")
    postal_code: str = Field(pattern=r"^\d{5}(-\d{4})?$")
    latitude: float | None = Field(default=None, ge=-90, le=90)
    longitude: float | None = Field(default=None, ge=-180, le=180)

    @field_validator("state")
    @classmethod
    def _upper(cls, v: str) -> str:
        return v.upper()

    @model_validator(mode="after")
    def _both_or_neither(self) -> "AddressIn":
        if (self.latitude is None) != (self.longitude is None):
            raise ValueError("latitude and longitude must be provided together")
        return self


class AddressOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    line1: str
    line2: str | None
    city: str
    state: str
    postal_code: str
    latitude: float | None
    longitude: float | None
    geocode_status: str


_TEXT_FIELDS = ("line1", "line2", "city", "state", "postal_code")


async def apply_address(obj: Any, a: AddressIn) -> None:
    """Copy address text onto `obj` and set its map point.

    Priority: explicit coordinates from the client > geocoder > nothing (status 'failed').
    The point is only re-geocoded when the text actually changed.
    """
    changed = any(getattr(obj, f, None) != getattr(a, f) for f in _TEXT_FIELDS)
    for f in _TEXT_FIELDS:
        setattr(obj, f, getattr(a, f))
    if a.latitude is not None and a.longitude is not None:
        obj.location, obj.geocode_status = point(a.latitude, a.longitude), "manual"
    elif changed or obj.location is None:
        coords = await get_geocoder().geocode(f"{a.line1}, {a.city}, {a.state} {a.postal_code}")
        if coords:
            obj.location, obj.geocode_status = point(*coords), "ok"
        else:
            obj.location, obj.geocode_status = None, "failed"
    obj.geocoded_at = datetime.now(UTC) if hasattr(obj, "geocoded_at") else None